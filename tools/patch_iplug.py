#!/usr/bin/env python3
"""Generate marked adapter fixes; leave the pinned upstream checkout untouched."""
import argparse
from pathlib import Path

p = argparse.ArgumentParser()
p.add_argument("upstream", type=Path)
p.add_argument("output", type=Path)
a = p.parse_args()
a.output.mkdir(parents=True, exist_ok=True)
source = (a.upstream / "IPlug/CLAP/IPlugCLAP.cpp").read_text()


def replace(old, new):
    global source
    if source.count(old) != 1:
        raise RuntimeError(f"Pinned source drift: {old[:70]}")
    source = source.replace(old, new)


replace(
    "return pStream->write(pStream, chunk.GetData(), chunk.Size()) == chunk.Size();",
    """// TopEnd adapter fix: CLAP streams may perform partial writes.
  int64_t offset = 0;
  while (offset < chunk.Size()) {
    const int64_t written = pStream->write(pStream, chunk.GetData() + offset, chunk.Size() - offset);
    if (written <= 0 || written > chunk.Size() - offset) return false;
    offset += written;
  }
  return true;""",
)
replace(
    "if (restoredOK)\n    OnRestoreState();",
    """if (restoredOK) {
    OnRestoreState();
    GetClapHost().paramsRescan(CLAP_PARAM_RESCAN_VALUES);
  }""",
)
replace(
    "pParam->GetDisplay(value, isDoubleType, str);",
    "pParam->GetDisplay(isDoubleType ? pParam->FromNormalized(value) : pParam->Constrain(value), false, str);",
)
replace(
    "if (size < str.GetLength())", "if (size <= static_cast<uint32_t>(str.GetLength()))"
)
replace(
    "pConfig->has_main_input = pConfig->input_port_count > 1;",
    "pConfig->has_main_input = pConfig->input_port_count > 0;",
)
replace(
    "pConfig->has_main_output = pConfig->output_port_count > 1;",
    "pConfig->has_main_output = pConfig->output_port_count > 0;",
)
(a.output / "IPlugCLAP.cpp").write_text(
    "// TopEnd-modified adapter generated by tools/patch_iplug.py; upstream license follows.\n"
    + source
)

# Clang 21 diagnoses this mixed enum arithmetic. Preserve its integer result.
source = (a.upstream / "IGraphics/Platforms/IGraphicsMac_view.mm").read_text()
replace(
    "code += kVK_F1 - NSF1FunctionKey;",
    "code += static_cast<int>(kVK_F1) - static_cast<int>(NSF1FunctionKey);",
)
(a.output / "IGraphicsMac_view.mm").write_text(
    "// TopEnd compiler compatibility change; upstream license follows.\n" + source
)

# This property path is not the process callback; a vector makes the VLA portable.
source = (a.upstream / "IPlug/AUv2/IPlugAU.cpp").read_text()
replace(
    "char buffer[bufferSize];\n      if (CFStringGetCString(inStr, buffer, bufferSize, kCFStringEncodingUTF8))",
    "std::vector<char> buffer(static_cast<size_t>(bufferSize));\n      if (CFStringGetCString(inStr, buffer.data(), bufferSize, kCFStringEncodingUTF8))",
)
replace("mTrackName.Set(buffer);", "mTrackName.Set(buffer.data());")
# Host bypass: upstream resets the plugin from the property thread, racing the
# render thread and restarting every filter, then hard-switches to pass-through.
# TopEnd keeps processing and crossfades host bypass inside ProcessBlock.
replace(
    "      SetBypassed(bypassed);\n      \n      // TODO: should the following be called here?\n      OnActivate(!bypassed);\n      OnReset();\n",
    "      // TopEnd adapter fix: ProcessBlock crossfades host bypass; no reset here.\n      SetBypassed(bypassed);\n",
)
replace(
    "    if (_this->GetBypassed())\n    {\n      _this->PassThroughBuffers((AudioSampleType) 0, nFrames);",
    "    if (false) // TopEnd adapter fix: ProcessBlock crossfades host bypass.\n    {\n      _this->PassThroughBuffers((AudioSampleType) 0, nFrames);",
)
(a.output / "IPlugAU.cpp").write_text(
    "// TopEnd compiler compatibility change; upstream license follows.\n#include <vector>\n"
    + source
)

# Host bypass: process and crossfade inside ProcessBlock instead of a hard switch.
source = (a.upstream / "IPlug/VST3/IPlugVST3_ProcessorBase.cpp").read_text()
replace(
    "    if (GetBypassed())\n    {\n      if (sampleSize == kSample32)",
    "    if (false) // TopEnd adapter fix: ProcessBlock crossfades host bypass.\n    {\n      if (sampleSize == kSample32)",
)
(a.output / "IPlugVST3_ProcessorBase.cpp").write_text(
    "// TopEnd bypass behavior change generated by tools/patch_iplug.py; upstream license follows.\n"
    + source
)

# The SDK's inclusive int64 upper bound rounds to 2^63 in double precision.
# An exclusive, exactly representable bound prevents an out-of-range cast.
source = (
    a.upstream / "Dependencies/IPlug/VST3_SDK/base/source/fstring.cpp"
).read_text()
replace(
    "value <= std::numeric_limits<int64>::max () &&\n\t                                   value >= std::numeric_limits<int64>::lowest ()",
    "value < -static_cast<double> (std::numeric_limits<int64>::lowest ()) &&\n\t                                   value >= static_cast<double> (std::numeric_limits<int64>::lowest ())",
)
(a.output / "fstring.cpp").write_text(
    "// TopEnd numeric boundary correction; upstream SDK license follows.\n" + source
)
